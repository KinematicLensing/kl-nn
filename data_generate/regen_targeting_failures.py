#!/usr/bin/env python3
"""Regenerate measured-axis FITS whose targeting measurement had failed.

Reads the combined failure list (dataset, part, ID) written by
``scan_targeting_failures_threaded.py``, takes rows
[task*per, (task+1)*per), and for each galaxy:

1. moves the old FITS into ``fits/_targeting_fix_backup/<dataset>/part_<n>/``;
2. reruns ``generate_fits.py`` with the same sample row (fixed targeting);
3. checks that the new image is bit-identical to the old one (the image does
   not depend on fiber positions) and records the new TGTHSMOK and TGTPA.

If generation fails, the old file is moved back. One result CSV per task.
"""

from __future__ import annotations

from argparse import ArgumentParser
import csv
from pathlib import Path
import shutil
import subprocess
import sys

import numpy as np
import pandas as pd
from astropy.io import fits

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from generate_fits_wrapper import build_generate_command  # noqa: E402

S = Path("/ocean/projects/phy250048p/shared")
FITS_ROOT = S / "fits"
BACKUP_ROOT = FITS_ROOT / "_targeting_fix_backup"
SAMPLES = S / "samples"


def image_and_header(path: Path):
    with fits.open(path) as hdul:
        image = [h.data for h in hdul if h.data is not None and h.data.ndim == 2
                 and h.data.shape == (48, 48)][-1].astype(np.float64)
        return image, dict(hdul[0].header)


def main(argv=None):
    p = ArgumentParser(description=__doc__)
    p.add_argument("--list", type=Path, required=True)
    p.add_argument("--task", type=int, required=True, help="zero-based task index")
    p.add_argument("--per", type=int, default=100)
    p.add_argument("--out-dir", type=Path, required=True)
    a = p.parse_args(argv)

    todo = pd.read_csv(a.list).iloc[a.task * a.per:(a.task + 1) * a.per]
    out_rows = []
    for dataset, group in todo.groupby("dataset", sort=False):
        table = pd.read_csv(SAMPLES / f"{dataset}.csv", float_precision="round_trip")
        table = table.set_index(table["ID"].astype(int), drop=False)
        for _, r in group.iterrows():
            gid, part = int(r.ID), int(r.part)
            path = FITS_ROOT / dataset / f"part_{part}" / f"gal_{gid}.fits"
            backup = BACKUP_ROOT / dataset / f"part_{part}" / f"gal_{gid}.fits"
            if backup.exists() and path.exists():
                # Already regenerated by an earlier run: verify and record only.
                old_image, old_header = image_and_header(backup)
                new_image, new_header = image_and_header(path)
                out_rows.append((dataset, part, gid, int(new_header["TGTHSMOK"]),
                                 old_header["TGTPA"], new_header["TGTPA"],
                                 bool(np.array_equal(old_image, new_image))))
                continue
            if backup.exists():
                old_image, old_header = image_and_header(backup)  # interrupted run
            else:
                old_image, old_header = image_and_header(path)
                backup.parent.mkdir(parents=True, exist_ok=True)
                shutil.move(str(path), str(backup))
            cmd = build_generate_command(table.loc[gid], part=part, dataset=dataset)
            done = subprocess.run(cmd, capture_output=True, text=True)
            if done.returncode != 0 or not path.exists():
                if path.exists():
                    path.unlink()
                shutil.move(str(backup), str(path))
                raise RuntimeError(f"{dataset} ID {gid}: generation failed\n{done.stderr[-2000:]}")
            new_image, new_header = image_and_header(path)
            same = bool(np.array_equal(old_image, new_image))
            out_rows.append((dataset, part, gid, int(new_header["TGTHSMOK"]),
                             old_header["TGTPA"], new_header["TGTPA"], same))
            if not same:
                raise RuntimeError(f"{dataset} ID {gid}: image changed after regeneration")
    a.out_dir.mkdir(parents=True, exist_ok=True)
    with (a.out_dir / f"task_{a.task:04d}.csv").open("w", newline="") as h:
        w = csv.writer(h)
        w.writerow(["dataset", "part", "ID", "new_TGTHSMOK", "old_TGTPA", "new_TGTPA", "image_identical"])
        w.writerows(out_rows)
    n_ok = sum(r[3] == 1 for r in out_rows)
    print(f"task {a.task}: regenerated {len(out_rows)}, HSM ok {n_ok}, unweighted fallback {len(out_rows) - n_ok}")


if __name__ == "__main__":
    main()
